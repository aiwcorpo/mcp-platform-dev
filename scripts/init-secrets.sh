#!/usr/bin/env bash
# Generates .secrets/dev.env with random dev-only passwords, client secrets and tokens.
# Values are NOT FOR PRODUCTION. Existing values are kept (passwords stay stable across `make up`);
# keys added in newer versions of this script are appended.
set -euo pipefail

root="$(cd "$(dirname "$0")/.." && pwd)"
out="$root/.secrets/dev.env"

rnd() { openssl rand -hex "${1:-24}"; }
# 160-bit TOTP seed in Base32 (RFC 4648, as authenticator apps expect it)
seed32() { python3 -c 'import base64, os; print(base64.b32encode(os.urandom(20)).decode())'; }

wanted() {
  cat <<EOF
KC_BOOTSTRAP_ADMIN_USERNAME=admin
KC_BOOTSTRAP_ADMIN_PASSWORD=$(rnd 16)
KC_USER_ALICE_PASSWORD=alice-$(rnd 6)
KC_USER_BOB_PASSWORD=bob-$(rnd 6)
KC_USER_CAROL_PASSWORD=carol-$(rnd 6)
KC_USER_MALLORY_PASSWORD=mallory-$(rnd 6)
KC_USER_ALICE_OTP_SEED=$(seed32)
KC_USER_BOB_OTP_SEED=$(seed32)
KC_USER_CAROL_OTP_SEED=$(seed32)
KC_CLIENT_MCP_GATEWAY_SECRET=$(rnd)
MCP_ACTIVITY_CURSOR_KEY=$(rnd 32)
MCP_LIST_CURSOR_KEY=$(rnd 32)
KC_CLIENT_MCP_PORTAL_BFF_SECRET=$(rnd)
KC_CLIENT_MCP_CREDENTIAL_BROKER_SECRET=$(rnd)
KC_CLIENT_MCP_GATEWAY_ADMIN_SECRET=$(rnd)
KC_CLIENT_OPENSEARCH_SECRET=$(rnd)
BAO_ROOT_TOKEN=dev-root-$(rnd 12)
BAO_BROKER_ROLE_ID=mcp-credential-broker
BAO_BROKER_SECRET_ID=$(rnd)
REDIS_ADMIN_PASSWORD=$(rnd)
REDIS_GATEWAY_PASSWORD=$(rnd)
REDIS_BROKER_PASSWORD=$(rnd)
REDIS_MCP_JIRA_PASSWORD=$(rnd)
REDIS_MCP_CONFLUENCE_PASSWORD=$(rnd)
REDIS_MCP_GITLAB_PASSWORD=$(rnd)
REDIS_MCP_SERVICEDESK_PASSWORD=$(rnd)
REDIS_MCP_OPENSEARCH_PASSWORD=$(rnd)
POSTGRES_PASSWORD=$(rnd)
GATEWAY_DB_PASSWORD=$(rnd)
BROKER_DB_PASSWORD=$(rnd)
TLS_STORE_PASSWORD=$(rnd 12)
JIRA_MOCK_ADMIN_PASSWORD=$(rnd)
MOCK_ADMIN_PASSWORD=$(rnd)
GITLAB_OAUTH_CLIENT_SECRET=$(rnd)
SERVICEDESK_API_KEY=sd-$(rnd)
REDIS_PORTAL_BFF_PASSWORD=$(rnd)
EOF
}

mkdir -p "$root/.secrets"
chmod 700 "$root/.secrets"
umask 077
if [[ ! -f "$out" ]]; then
  echo "# NOT FOR PRODUCTION - generated by scripts/init-secrets.sh on $(date -u +%Y-%m-%dT%H:%M:%SZ)" > "$out"
fi

added=0
while IFS= read -r line; do
  key="${line%%=*}"
  if ! grep -q "^$key=" "$out"; then
    echo "$line" >> "$out"
    added=$((added + 1))
  fi
done < <(wanted)
echo "secrets: $out ($added new)"
