#!/bin/sh
# DEV ONLY. Initialises and unseals the dev OpenBao, and keeps doing so: the loop unseals again after every restart of the
# server (Stop/Start in Docker Desktop, docker restart, crash). One key share, one threshold, stored next to the root token in
# /keys (the host's .secrets/openbao, mode 600). A production OpenBao needs an auto-unseal seal or a split key; this script
# exists because the dev stack must come back from Stop without a person at the keyboard.
#
# Neither the key nor the root token is ever printed: output of `bao operator init` goes into variables, files are written
# with umask 077, the key reaches `bao write sys/unseal` through stdin (`bao operator unseal` takes it only as an argument or a tty).
#
# The stack uses a fixed token id (BAO_ROOT_TOKEN of .secrets/dev.env). After the first init this script creates a root-policy
# token with that id, so every script and compose service keeps working; the token generated by init is kept in /keys/root-token.
set -u
export BAO_ADDR="${BAO_ADDR:-http://openbao:8200}"
keys=/keys
umask 077

say() { echo "openbao-unseal: $*"; }

store_init_output() {
  out="$1"
  key="$(printf '%s' "$out" | sed -n '/unseal_keys_b64/,/\]/{/unseal_keys_b64/d;/\]/d;s/^ *"\([^"]*\)".*/\1/p;}' | head -1)"
  root="$(printf '%s' "$out" | sed -n 's/.*"root_token": *"\([^"]*\)".*/\1/p' | head -1)"
  [ -n "$key" ] && [ -n "$root" ] || { say "init output not understood, keys NOT stored"; return 1; }
  printf '%s\n' "$key" > "$keys/unseal-key.tmp" && printf '%s\n' "$root" > "$keys/root-token.tmp" || return 1
  chmod 600 "$keys/unseal-key.tmp" "$keys/root-token.tmp"
  mv "$keys/unseal-key.tmp" "$keys/unseal-key" && mv "$keys/root-token.tmp" "$keys/root-token"
}

ensure_stack_token() {
  [ -n "${BAO_ROOT_TOKEN:-}" ] || return 0
  BAO_TOKEN="$BAO_ROOT_TOKEN" bao token lookup >/dev/null 2>&1 && return 0
  [ -s "$keys/root-token" ] || { say "root-token missing in $keys, the stack token cannot be created"; return 1; }
  printf '%s' "$BAO_ROOT_TOKEN" \
    | BAO_TOKEN="$(cat "$keys/root-token")" bao write auth/token/create id=- policies=root no_parent=true ttl=0 display_name=dev-stack-root >/dev/null 2>&1
  if BAO_TOKEN="$BAO_ROOT_TOKEN" bao token lookup >/dev/null 2>&1; then say "stack token created"; else say "stack token could not be created"; return 1; fi
}

last=""
note() { [ "$last" = "$1" ] || { say "$1"; last="$1"; }; }

while true; do
  status="$(bao status -format=json 2>/dev/null)"
  rc=$?
  if [ "$rc" -eq 1 ] || [ -z "$status" ]; then
    note "waiting for the server"
  elif printf '%s' "$status" | grep -q '"initialized": *false'; then
    note "not initialised, running init"
    if out="$(bao operator init -key-shares=1 -key-threshold=1 -format=json 2>/dev/null)"; then
      if store_init_output "$out"; then note "initialised, keys stored in $keys (mode 600)"; else note "INIT DONE BUT KEYS NOT STORED: data unusable, remove the volume openbao-data and restart"; fi
    else
      note "init failed"
    fi
    out=""
  elif printf '%s' "$status" | grep -q '"sealed": *true'; then
    if [ -s "$keys/unseal-key" ]; then
      note "sealed, unsealing"
      if bao write sys/unseal key=- < "$keys/unseal-key" >/dev/null 2>&1; then ensure_stack_token; else note "unseal failed"; fi
    else
      note "SEALED AND NO KEY in $keys/unseal-key: restore the file or remove the volume openbao-data (secrets are lost)"
    fi
  else
    ensure_stack_token && note "unsealed"
  fi
  sleep 2
done
